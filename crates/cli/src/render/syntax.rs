impl Lang {
    pub(super) fn syntax(self) -> Option<&'static Syntax> {
        match self {
            Lang::Rust => Some(&RUST),
            Lang::Python => Some(&PYTHON),
            Lang::Script => Some(&SCRIPT),
            Lang::CLike => Some(&CLIKE),
            Lang::Shell => Some(&SHELL),
            Lang::Json => Some(&JSON),
            Lang::Toml => Some(&TOML),
            Lang::Yaml => Some(&YAML),
            Lang::Other => None,
        }
    }
}
