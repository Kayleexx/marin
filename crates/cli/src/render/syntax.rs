//! The few facts about each language that the lexer needs. Anything not listed here stays plain.

pub struct Syntax {
    pub(super) keywords: &'static [&'static str],
    pub(super) line_comment: &'static str,
    pub(super) block_comment: bool,
    pub(super) quotes: &'static [char],
    pub(super) triple: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Rust,
    Python,
    Script,
    CLike,
    Shell,
    Json,
    Toml,
    Yaml,
    /// Code in a language this lexer does not know: shown without colors.
    Other,
}

